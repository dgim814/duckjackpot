export function useSaleText() {
  const { lang } = useI18n()
  const d = lang === 'en' ? EN : RU
  return {
    d,
    err: (code: string) => d.errors[code] ?? d.errors.default,
    fmt: (s: string, vars: Record<string, string | number>) => s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? '')),
  }
}
