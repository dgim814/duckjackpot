// Compiles the OFFICIAL TEP-62 reference NFT contracts (ton-blockchain/token-contract, pinned commit)
// with the official FunC compiler (@ton-community/func-js) and checks them against
// src/nftSale/contracts/referenceCode.ts. Usage: node scripts/nft-reference-compile.mjs [--write]
import { compileFunc } from '@ton-community/func-js'
import { Cell } from '@ton/core'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const COMMIT = '21e7844fa6dbed34e0f4c70eb5f0824409640a30'
const RAW = `https://raw.githubusercontent.com/ton-blockchain/token-contract/${COMMIT}`
const OUT = join(dirname(fileURLToPath(import.meta.url)), '../src/nftSale/contracts/referenceCode.ts')

async function get(path) {
  const r = await fetch(`${RAW}/${path}`)
  if (!r.ok) throw new Error(`${path}: HTTP ${r.status}`)
  return r.text()
}
const sources = {
  'stdlib.fc': await get('stdlib.fc'),
  'params.fc': await get('nft/params.fc'),
  'op-codes.fc': await get('nft/op-codes.fc'),
  'nft-item.fc': await get('nft/nft-item.fc'),
  'nft-collection.fc': await get('nft/nft-collection.fc'),
}
async function build(main) {
  const r = await compileFunc({ targets: ['stdlib.fc', 'params.fc', 'op-codes.fc', main], sources })
  if (r.status !== 'ok') throw new Error(`${main}: ${r.message}`)
  const cell = Cell.fromBase64(r.codeBoc)
  return { boc: r.codeBoc, hash: cell.hash().toString('hex') }
}
const item = await build('nft-item.fc')
const collection = await build('nft-collection.fc')
const file = `// GENERATED by scripts/nft-reference-compile.mjs — do not edit by hand.
// Official TEP-62 reference contracts: https://github.com/ton-blockchain/token-contract/tree/${COMMIT}/nft
// compiled with @ton-community/func-js. Unmodified.
export const REFERENCE_COMMIT = '${COMMIT}'
export const NFT_ITEM_CODE_BOC = '${item.boc}'
export const NFT_ITEM_CODE_HASH = '${item.hash}'
export const NFT_COLLECTION_CODE_BOC = '${collection.boc}'
export const NFT_COLLECTION_CODE_HASH = '${collection.hash}'
`
if (process.argv.includes('--write')) {
  writeFileSync(OUT, file)
  console.log('written', OUT)
} else {
  const same = readFileSync(OUT, 'utf8') === file
  console.log(same ? 'OK: committed code matches the official sources' : 'MISMATCH: committed code differs from the official sources')
  if (!same) process.exit(1)
}
console.log('item', item.hash, '\ncollection', collection.hash)
